#[cfg(test)]
mod tests {
    use super::PACKED_TRI_TABLE;

    fn edge(case: usize, slot: usize) -> u32 {
        let word = PACKED_TRI_TABLE[case * 2 + slot / 8];
        (word >> ((slot % 8) * 4)) & 0xF
    }

    #[test]
    fn every_case_is_terminated_and_contains_complete_triangles() {
        for case in 0..256 {
            let mut edge_count = 0;
            while edge_count < 16 && edge(case, edge_count) != 0xF {
                assert!(
                    edge(case, edge_count) < 12,
                    "case {case}, slot {edge_count}"
                );
                edge_count += 1;
            }
            assert!(edge_count < 16, "case {case} has no sentinel");
            assert_eq!(edge_count % 3, 0, "case {case} has an incomplete triangle");
            for slot in edge_count..16 {
                assert_eq!(edge(case, slot), 0xF, "case {case}, slot {slot}");
            }
        }
    }

    #[test]
    fn empty_and_single_corner_cases_match_the_canonical_table() {
        assert_eq!(
            (0..16).map(|slot| edge(0, slot)).collect::<Vec<_>>(),
            vec![0xF; 16]
        );
        assert_eq!(&PACKED_TRI_TABLE[2..4], &[0xFFFF_F380, 0xFFFF_FFFF]);
        assert_eq!(
            (0..16).map(|slot| edge(255, slot)).collect::<Vec<_>>(),
            vec![0xF; 16]
        );
    }
}
